import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../widgets/_shared/time.js', import.meta.url), 'utf8');
const { clockParts, dayDifference } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const winter = new Date('2026-01-01T00:30:05Z');
assert.equal(clockParts(winter, 'UTC').time, '00:30:05');
assert.equal(clockParts(winter, 'Asia/Shanghai').time, '08:30:05');
assert.equal(clockParts(winter, 'America/New_York').time, '19:30:05');
assert.equal(clockParts(winter, 'America/New_York').zone, 'EST');
assert.equal(clockParts(winter, 'America/Los_Angeles').zone, 'PST');
const summer = new Date('2026-07-01T00:30:05Z');
assert.equal(clockParts(summer, 'America/New_York').zone, 'EDT');
assert.equal(clockParts(summer, 'America/Los_Angeles').zone, 'PDT');
assert.equal(clockParts(summer, 'America/New_York').time, '20:30:05');
assert.equal(dayDifference('2026-01-01', '2025-12-31'), '+1天');
assert.equal(dayDifference('2025-12-31', '2026-01-01'), '−1天');
assert.equal(dayDifference('2026-01-01', '2026-01-01'), '同日');
assert.equal(clockParts(new Date('2026-01-01T00:00:00Z'), 'UTC').time, '00:00:00');
console.log('PASS: UTC, Beijing, NY/LA winter and summer, midnight, cross-year day differences');
